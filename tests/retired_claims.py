def find_retired(text: str):
    """text 에서 폐기된 주장을 찾아 [(매치문자열, 사유)] 로 돌려준다."""
    hits = []
    for pattern, why in RETIRED:
        for m in re.finditer(pattern, text):
            hits.append((m.group(0), why))
    return hits
